"""Extract the user's other 21 posters using the accepted v30 point format.
Explicit source outlines exclude typography and inset images. Existing seven
Azure Dragon assets are never regenerated by this script.
"""
from pathlib import Path
import argparse, base64, hashlib, json, struct
from PIL import Image, ImageDraw, ImageFilter, ImageFont
import numpy as np

def extract(config, input_dir, output_dir, previews):
 source=input_dir/config['file']; image=Image.open(source).convert('RGB'); w,h=image.size
 if (w,h)!=(707,1060): raise ValueError('Unexpected source size: '+str(source))
 mask=Image.new('L',(w,h)); ImageDraw.Draw(mask).polygon(config['outline'],fill=255)
 for part in config.get('parts',[]):ImageDraw.Draw(mask).polygon(part,fill=255)
 soft=np.asarray(mask.filter(ImageFilter.GaussianBlur(1.8*h/1536)),dtype=float)/255
 rgb=np.asarray(image,dtype=float); bright=rgb.max(axis=2)/255
 valid=(soft>.35)&(bright>.10)
 # Neutral letters in the left title block are not part of pale-cyan ribbons.
 neutral=(rgb.max(axis=2)-rgb.min(axis=2))<rgb.max(axis=2)*.1
 valid[:280,:278]&=~neutral[:280,:278]
 yy,xx=np.where(valid); left,right=int(xx.min()),int(xx.max()); top,bottom=int(yy.min()),int(yy.max())
 width,height=right-left+1,bottom-top+1
 lum=rgb.mean(axis=2)/255; gy,gx=np.gradient(lum)
 protect=np.zeros((h,w),dtype=bool)
 for x1,y1,x2,y2 in config['face']: protect[y1:y2,x1:x2]=True
 weights=(.15+bright[yy,xx]**1.25+np.clip(np.hypot(gx,gy)[yy,xx]*5,0,1.6)+protect[yy,xx]*1.8)*soft[yy,xx]
 rng=np.random.default_rng(230028+config['id']); count=96000
 if len(yy)<count: raise ValueError('Too few subject samples: '+config['title'])
 chosen=rng.choice(len(yy),count,replace=len(yy)<count,p=weights/weights.sum()); yy,xx=yy[chosen],xx[chosen]
 depth=np.asarray(Image.fromarray(np.uint8(lum*255)).filter(ImageFilter.GaussianBlur(4*h/1536)),dtype=float)/255
 packed=bytearray()
 for y,x in zip(yy,xx):
  px=round(((x+.5+rng.uniform(-.32,.32)-left)/height-width/height/2)*1000)
  py=round(((y+.5+rng.uniform(-.32,.32)-top)/height-.5)*1000)
  pz=round((depth[y,x]-.38)*.075*1000)
  color=np.minimum(255,np.power(rgb[y,x]/255,.86)*255*1.05).astype(int)
  packed.extend(struct.pack('<hhhBBB',px,py,pz,*color))
 edge=np.asarray(mask.filter(ImageFilter.GaussianBlur(12*h/1536)),dtype=float)/255
 edge_alpha=.22+.78*np.clip((edge[yy,xx]-.43)/.49,0,1)**.75
 edge_alpha[protect[yy,xx]]=1
 ey,ex=np.gradient(edge); weathering=bytearray(); active=0
 for y,x in zip(yy,xx):
  proximity=float(np.clip((.94-edge[y,x])/.46,0,1)); norm=float(np.hypot(ex[y,x],ey[y,x]))
  if protect[y,x] or proximity<.08 or norm<1e-7 or active>=10500:
   weathering.extend(struct.pack('<hh',0,0)); continue
  distance=(.09+.11*proximity)*rng.uniform(.72,1)
  weathering.extend(struct.pack('<hh',round(-ex[y,x]/norm*distance*1000),round(-ey[y,x]/norm*distance*1000))); active+=1
 if active>11000: raise ValueError('Too many dynamic edge grains: '+str(active))
 item={k:config[k] for k in ['id','name','title','pinyin']}
 item.update(style='heritage-poster',group=config['id']//7,count=count,aspect=width/height,source=config['file'],sourceSha256=hashlib.sha256(source.read_bytes()).hexdigest(),sourceSize=[w,h],crop=[left,top,width,height],protectedFaces=config['face'],encoding='base64-int16le-xyz-uint8-rgb/9bytes',depthNote='v30 image-based parallax, not a 3D mesh.',data=base64.b64encode(packed).decode(),edgeAlpha=base64.b64encode(np.uint8(np.round(edge_alpha*255)).tobytes()).decode(),weathering=dict(kind='surface-edge',count=count,active=active,encoding='base64-int16le-xy/4bytes',data=base64.b64encode(weathering).decode()))
 output=output_dir/f"{config['id']:02d}-{config['slug']}.json";output.write_text(json.dumps(item,ensure_ascii=False,separators=(',',':')),encoding='utf8')
 # Technical point-cloud preview, not a replacement for the user's artwork.
 preview=Image.new('RGB',(w,h),'#080d13'); dots=ImageDraw.Draw(preview)
 colors=np.minimum(255,np.power(rgb[yy,xx]/255,.86)*255*1.05).astype(np.uint8)
 for x,y,color in zip(xx,yy,colors): dots.point((int(x),int(y)),fill=tuple(map(int,color)))
 preview.save(previews/f"{config['id']:02d}-{config['slug']}.png")
 return {k:item[k] for k in ['id','name','title','pinyin','count','source','sourceSha256','sourceSize','crop','protectedFaces']}|{'active':active,'asset':output.name}


if __name__=='__main__':
 parser=argparse.ArgumentParser();parser.add_argument('--input-dir',default='D:/Desktop');parser.add_argument('--previews',default='../posters-v33-previews');parser.add_argument('--ids',default='')
 args=parser.parse_args();previews=Path(args.previews);previews.mkdir(parents=True,exist_ok=True)
 configs=json.loads(Path('scripts/poster-outlines-v33.json').read_text(encoding='utf8'))
 names=json.loads(Path('dist/data/statues.json').read_text(encoding='utf8'))['items']
 chosen=set(map(int,args.ids.split(','))) if args.ids else None
 reports=[]
 for config in configs:
  if chosen and config['id'] not in chosen: continue
  config.update({k:names[config['id']][k] for k in ['name','title','pinyin']})
  output=Path('dist/data')/config['group'];output.mkdir(parents=True,exist_ok=True)
  report=extract(config,Path(args.input_dir),output,previews);reports.append(report);print(json.dumps(report,ensure_ascii=True),flush=True)
 if not chosen:
  (previews/'extraction.json').write_text(json.dumps(reports,ensure_ascii=False,indent=2),encoding='utf8')
 for group in ['xuanwu','baihu','zhuque']:
  selected=[c for c in configs if c['group']==group and (not chosen or c['id'] in chosen)]
  if not selected:continue
  sheet=Image.new('RGB',(1416,1140),'#080d13');draw=ImageDraw.Draw(sheet);font=ImageFont.truetype('C:/Windows/Fonts/msyh.ttc',18)
  for i,c in enumerate(selected):
   preview=previews/f"{c['id']:02d}-{c['slug']}.png"
